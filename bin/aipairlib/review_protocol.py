def endless_poke_claude_pass(task_list, next_ask):
    """Codex が「レビュー合格」を出した直後に Claude へ送る文面。"""
    return ("【自動レビューループ】Codexのレビューは合格でした。まず"
            f"`{task_list}` の**完了した項目を `- [x]` にチェック**してください（これをしないとループが"
            "収束しません）。次に、着手可な `- [ ]` から**次の1件**に着手してください。着手する項目名を"
            "明示してから実装し、終わったら何をしたか簡潔に述べてターンを終えてください。"
            "⚠ 着手した項目が**AI だけでは進められない**（人間の承認・認証情報・管理者操作・外部反映待ち・"
            "実機確認・現在の環境から実行不能）と分かったら、その `- [ ]` を **`- [!]`** に変え、"
            "**直下に `blocker: 理由` を併記**してから、他の `- [ ]` があれば続行し、無ければ下記シグナルを"
            "出してください（`- [ ]` のまま放置しない）。"
            "あなたの返答は自動でCodexに共有されます—人間に伝言を頼まないでください"
            "（これは AI 同士の往復の話。上記のとおり**人間の対応が本当に必要なタスクを `[!]` で明示して"
            "止めるのは妨げない**。「人間へ頼るな」と「人間しか解けない時も止まるな」を混同しない）。"
            f"着手可な `- [ ]` が無く、あなたの側でやることが尽きている場合のみ、最終回答の【1行目】に "
            f"{next_ask} を単独で（同じ行に他の文字を書かず）出力してターンを終えてください"
            "（Codexが次の指示を出します）。それ以外の場合はこのシグナルを書かないこと。")


def endless_poke_codex_next(task_list, all_done, human_required):
    """Claude が「次をください」と言った時に Codex へ送る文面（次タスク選択・社長指示 §4）。

    選択順: 実行可能な `- [ ]` を優先し 1 件だけ指示 → 無ければ人間対応・外部依存の `- [!]`（保留）を
    確認し、`- [!]` が残るなら HUMAN_REQUIRED を宣言 → どちらも無ければ ALL_DONE。`- [!]` は AI では
    進められないので**再指示しない**。
    """
    return ("【自動レビューループ】Claudeは手持ちのタスクを終えました。`peer` で経緯を読み、"
            f"`{task_list}` から次を**この順序**で判定してください:\n"
            "① 実行可能な **`- [ ]`** があれば、その中から**1件だけ**選び、**その `- [ ]` 行を"
            "逐語で1行そのまま**引用した上で（relay の進捗検出に使うので改変しない）、「どのファイルで"
            "何をするか」が分かる具体性で指示する（シグナルは書かない）。\n"
            f"② `- [ ]` が無く、人間対応・外部依存の **`- [!]`（保留）** だけが残るなら、最終回答の"
            f"【1行目】に {human_required} を単独で（同じ行に他の文字を書かず）出力する"
            "（人間の対応待ちとしてループを停止）。\n"
            f"③ `- [ ]` も `- [!]` も無ければ、最終回答の【1行目】に {all_done} を単独で出力する"
            "（全タスク完了・ループ終了）。\n"
            "あなたの返答は自動でClaudeに共有されます—人間に伝言を頼まないでください"
            "（これは AI 同士の往復の話。②のように**人間しか解けないタスクだけが残るなら HUMAN_REQUIRED で"
            "止める**のは妨げない）。"
            "⚠ リストに無い作業を新規提案しないこと。**`- [!]`（保留）は AI では進められないので"
            "Claude に再指示しないこと**。②③のシグナルは該当する時だけ 1行目に単独で書き、"
            "①で指示する時はどちらも書かないこと。")


